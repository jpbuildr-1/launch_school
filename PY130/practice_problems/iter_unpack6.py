first, *middle, last = "hello"
print(f"First: {first}, Middle: {middle}, Last: {last}")

# The code will output is
# First: h, Middle: ['e', 'l', 'l'], Last: o
# The `first` element would contain the first element of the string "hello"
# The `last` element would contain the last element of the string "hello"
# The `middle` element would contain the elements between first and last
# in a list